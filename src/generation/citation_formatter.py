"""Citation Attribution Engine and Multi-Document Section Segregator.

Extracts, validates, and standardizes inline citations and structured
GroundedSection records connecting LLM claims to authoritative source chunks.
"""

import re
from typing import List, Tuple, Dict, Optional, Set
from collections import OrderedDict

from src.models.schemas import Chunk, Citation, GroundedSection

# Regex pattern matching: [Document Title | Publisher, Year | Source URL]
CITATION_REGEX = re.compile(
    r"\[\s*([^\|\]]+?)\s*\|\s*([^\|,\]]+?)\s*,\s*(\d{4})\s*\|\s*(https?://[^\s\]]+)\s*\]"
)


def format_citation_string(chunk: Chunk) -> str:
    """Format canonical citation string for a chunk: [Title | Publisher, Year | URL]."""
    return f"[{chunk.document_title} | {chunk.publisher}, {chunk.year} | {chunk.source_url}]"


def extract_and_validate_citations(
    response_text: str,
    source_chunks: List[Chunk],
) -> Tuple[str, List[Citation], List[GroundedSection]]:
    """Parse citations from synthesized text, validate provenance, and partition sections.
    
    Args:
        response_text: Raw markdown text generated by LLM synthesizer.
        source_chunks: Candidate chunks supplied as context to synthesizer.
        
    Returns:
        Tuple[str, List[Citation], List[GroundedSection]]:
            - Validated response text.
            - Deduplicated list of Citation objects.
            - Per-document GroundedSection objects.
    """
    chunk_map: Dict[str, Chunk] = {c.chunk_id: c for c in source_chunks}
    
    # Map title / url to source chunks for fast lookup
    doc_chunk_lookup: Dict[str, List[Chunk]] = {}
    for c in source_chunks:
        doc_chunk_lookup.setdefault(c.document_title.lower(), []).append(c)
        doc_chunk_lookup.setdefault(c.source_url.lower(), []).append(c)
        doc_chunk_lookup.setdefault(c.document_id.lower(), []).append(c)

    # 1. Extract inline citations from generated text
    extracted_citations: List[Citation] = []
    seen_citation_keys: Set[Tuple[str, str]] = set()

    matches = CITATION_REGEX.findall(response_text)
    for title, publisher, year_str, url in matches:
        title = title.strip()
        publisher = publisher.strip()
        year = int(year_str.strip())
        url = url.strip()
        
        key = (title.lower(), url.lower())
        if key in seen_citation_keys:
            continue
        seen_citation_keys.add(key)

        # Match back to nearest source chunk
        matched_chunk: Optional[Chunk] = None
        candidates = doc_chunk_lookup.get(title.lower()) or doc_chunk_lookup.get(url.lower())
        if candidates:
            matched_chunk = candidates[0]

        citation = Citation(
            document_title=matched_chunk.document_title if matched_chunk else title,
            document_name=matched_chunk.document_title if matched_chunk else title,
            publisher=matched_chunk.publisher if matched_chunk else publisher,
            year=matched_chunk.year if matched_chunk else year,
            source_url=matched_chunk.source_url if matched_chunk else url,
            section_heading=matched_chunk.section_heading if matched_chunk else "",
            chunk_id=matched_chunk.chunk_id if matched_chunk else None,
            verbatim_text=matched_chunk.content[:200] if matched_chunk else None,
            similarity_score=matched_chunk.similarity_score if matched_chunk else None,
        )
        extracted_citations.append(citation)

    # If no inline citations were extracted, construct citations from the source chunks
    if not extracted_citations and source_chunks:
        for c in source_chunks:
            key = (c.document_title.lower(), c.source_url.lower())
            if key not in seen_citation_keys:
                seen_citation_keys.add(key)
                extracted_citations.append(
                    Citation(
                        document_title=c.document_title,
                        document_name=c.document_title,
                        publisher=c.publisher,
                        year=c.year,
                        source_url=c.source_url,
                        section_heading=c.section_heading,
                        chunk_id=c.chunk_id,
                        verbatim_text=c.content[:200],
                        similarity_score=c.similarity_score,
                    )
                )

    # 2. Partition response text into GroundedSection records
    sections = _partition_grounded_sections(response_text, source_chunks, extracted_citations)

    return response_text, extracted_citations, sections


def _partition_grounded_sections(
    response_text: str,
    source_chunks: List[Chunk],
    citations: List[Citation],
) -> List[GroundedSection]:
    """Group response text into segregated GroundedSection records per document/publisher."""
    if not source_chunks:
        return []

    # Identify unique documents from source chunks
    docs_in_context: Dict[str, Chunk] = OrderedDict()
    for c in source_chunks:
        if c.document_id not in docs_in_context:
            docs_in_context[c.document_id] = c

    # If single document in context, the entire response is one section
    if len(docs_in_context) == 1:
        first = list(docs_in_context.values())[0]
        return [
            GroundedSection(
                publisher=first.publisher,
                document_title=first.document_title,
                document_name=first.document_title,
                source_url=first.source_url,
                content=response_text.strip(),
                summary_text=response_text.strip(),
                citations=citations,
            )
        ]

    # For multiple documents: attempt to split on markdown headers (### or ##)
    header_pattern = re.compile(r"^(#{1,3}\s+.+)$", re.MULTILINE)
    splits = header_pattern.split(response_text)

    # If header splits exist and match document titles or publishers
    grounded_sections: List[GroundedSection] = []
    current_header = ""
    current_body = ""

    # Parse headers and associated body blocks
    blocks: List[Tuple[str, str]] = []
    i = 0
    while i < len(splits):
        part = splits[i].strip()
        if header_pattern.match(part):
            header = part.lstrip("#").strip()
            body = splits[i + 1].strip() if (i + 1 < len(splits)) else ""
            blocks.append((header, body))
            i += 2
        else:
            if part:
                blocks.append(("", part))
            i += 1

    # Match parsed blocks against documents
    for header, body in blocks:
        matched_chunk: Optional[Chunk] = None
        header_lower = header.lower()
        for doc_id, chunk in docs_in_context.items():
            if (
                chunk.document_title.lower() in header_lower
                or chunk.publisher.lower() in header_lower
                or doc_id.lower() in header_lower
            ):
                matched_chunk = chunk
                break

        if matched_chunk:
            section_citations = [
                c for c in citations
                if c.document_title.lower() == matched_chunk.document_title.lower()
                or c.source_url.lower() == matched_chunk.source_url.lower()
            ]
            full_content = f"### {header}\n\n{body}" if header else body
            grounded_sections.append(
                GroundedSection(
                    publisher=matched_chunk.publisher,
                    document_title=matched_chunk.document_title,
                    document_name=matched_chunk.document_title,
                    source_url=matched_chunk.source_url,
                    content=full_content.strip(),
                    summary_text=body.strip(),
                    citations=section_citations,
                )
            )

    # Fallback if markdown headers didn't match documents cleanly
    if not grounded_sections:
        for doc_id, chunk in docs_in_context.items():
            doc_citations = [
                c for c in citations
                if c.document_title.lower() == chunk.document_title.lower()
                or c.source_url.lower() == chunk.source_url.lower()
            ]
            grounded_sections.append(
                GroundedSection(
                    publisher=chunk.publisher,
                    document_title=chunk.document_title,
                    document_name=chunk.document_title,
                    source_url=chunk.source_url,
                    content=response_text.strip(),
                    summary_text=response_text.strip(),
                    citations=doc_citations,
                )
            )

    # Consolidate sections by publisher to guarantee strict authority segregation
    if len(grounded_sections) > 1:
        consolidated: Dict[str, GroundedSection] = OrderedDict()
        for s in grounded_sections:
            if s.publisher not in consolidated:
                consolidated[s.publisher] = s
            else:
                existing = consolidated[s.publisher]
                combined_content = f"{existing.content}\n\n{s.content}".strip()
                combined_summary = f"{existing.summary_text or ''}\n\n{s.summary_text or ''}".strip()
                combined_citations = existing.citations[:]
                for cit in s.citations:
                    if cit not in combined_citations:
                        combined_citations.append(cit)
                consolidated[s.publisher] = GroundedSection(
                    publisher=existing.publisher,
                    document_title=existing.document_title if existing.document_title == s.document_title else f"{existing.publisher} Guidance",
                    document_name=existing.document_name,
                    source_url=existing.source_url,
                    content=combined_content,
                    summary_text=combined_summary,
                    citations=combined_citations,
                )
        return list(consolidated.values())

    return grounded_sections
